export const PixelIcon = memo(function PixelIcon({ name, size = 18, className, title }: { name: keyof typeof SPRITES | string; size?: number; className?: string; title?: string }) {
  const rows = SPRITES[name] ?? SPRITES.folder;
  const rects: React.ReactNode[] = [];
  rows.forEach((row, y) => {
    let x = 0;
    while (x < row.length) {
      const ch = row[x];
      if (ch === '.') {
        x++;
        continue;
      }
      let w = 1;
      while (x + w < row.length && row[x + w] === ch) w++;
      rects.push(<rect key={`${x}-${y}`} x={x} y={y} width={w} height={1} fill={P[ch] ?? 'currentColor'} />);
      x += w;
    }
  });
  return (
    <svg className={`pxicon ${className ?? ''}`} width={size} height={size} viewBox="0 0 12 12" shapeRendering="crispEdges" role={title ? 'img' : undefined} aria-hidden={title ? undefined : true} aria-label={title}>
      {rects}
    </svg>
  );
});

